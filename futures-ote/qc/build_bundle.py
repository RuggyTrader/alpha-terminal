"""Build the QuantConnect Cloud project files (qc/cloud/) from the canonical sources.

  python qc/build_bundle.py           rebuild qc/cloud/
  python qc/build_bundle.py --check   fail if qc/cloud/ is not exactly what the sources produce (used by tests)

The free tier allows 25 files of 32 KB per project (the project's research.ipynb counts), so packages are flattened:
ote_engine/strategy.py -> ote_strategy.py, mffu/rules.py -> mffu_rules.py, with imports rewritten to match. Nothing in
the strategy or the simulator is changed. at_build.py records the SHA-256 of every other file (main.py verifies them in
the cloud, so a paste error stops the run) and the fingerprint of the deterministic engine self-test computed here.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "cloud")
MAX_FILES = 24          # 25 per project on the free tier, one of them research.ipynb
MAX_BYTES = 32_000      # 32 KB per file (kept slightly under)
SOURCES = [
    ("qc/main.py", "main.py"), ("qc/at_stream.py", "at_stream.py"), ("qc/at_config.py", "at_config.py"),
    ("ote_engine/indicators.py", "ote_indicators.py"), ("ote_engine/strategy.py", "ote_strategy.py"), ("ote_engine/rolls.py", "ote_rolls.py"),
    ("ote_engine/report.py", "ote_report.py"), ("ote_engine/locked.py", "ote_locked.py"), ("ote_engine/data.py", "ote_data.py"),
    ("ote_engine/replay.py", "ote_replay.py"),
    ("mffu/rules.py", "mffu_rules.py"), ("mffu/account.py", "mffu_account.py"), ("mffu/calendar.py", "mffu_calendar.py"),
    ("mffu/t1_calendar.py", "mffu_t1_calendar.py"), ("mffu/compliance.py", "mffu_compliance.py"), ("mffu/instruments.py", "mffu_instruments.py"),
    ("mffu/evaluate.py", "mffu_evaluate.py"), ("mffu/experiments.py", "mffu_experiments.py"), ("mffu/dashboard.py", "mffu_dashboard.py"),
    ("mffu/execution.py", "mffu_execution.py"), ("mffu/sources.py", "mffu_sources.py"),
]
PKG = {"ote_engine": "ote", "mffu": "mffu"}

sys.path[:0] = [HERE, ROOT]
from at_stream import normalized, file_sha, bundle_sha   # noqa: E402  (pure helpers; no QuantConnect needed)


def rewrite(text: str, pkg: str) -> str:
    pre = PKG.get(pkg)
    if pre:
        text = re.sub(r"(?m)^(\s*)from \. import (\w+) as (\w+)", lambda m: f"{m.group(1)}import {pre}_{m.group(2)} as {m.group(3)}", text)
        text = re.sub(r"(?m)^(\s*)from \.(\w+) import ", lambda m: f"{m.group(1)}from {pre}_{m.group(2)} import ", text)
    for p, pre2 in PKG.items():
        text = re.sub(rf"(?m)^(\s*)from {p}\.(\w+) import ", lambda m: f"{m.group(1)}from {pre2}_{m.group(2)} import ", text)
        text = re.sub(rf"(?m)^(\s*)from {p} import (\w+)\b", lambda m: f"{m.group(1)}import {pre2}_{m.group(2)} as {m.group(2)}", text)
    return text


def build():
    files = {}
    for src, dst in SOURCES:
        with open(os.path.join(ROOT, src), encoding="utf-8") as f:
            text = rewrite(f.read(), src.split("/")[0])
        left = re.findall(r"(?m)^\s*(?:from \.|from (?:ote_engine|mffu)[ .]|import (?:ote_engine|mffu)\b).*$", text)
        if left:
            raise SystemExit(f"{dst}: unrewritten package import(s): {left}")
        files[dst] = normalized(text)
    manifest = {k: file_sha(v) for k, v in files.items()}
    return files, manifest


def selftest_in(dirpath: str) -> str:
    """Run the self-test from the flat bundle alone (proves the rewritten imports work) and return its fingerprint."""
    code = "import sys; sys.path.insert(0, sys.argv[1]); import at_stream; print(at_stream.selftest())"
    r = subprocess.run([sys.executable, "-I", "-B", "-W", "ignore", "-c", code, dirpath], capture_output=True, text=True, cwd=dirpath)
    if r.returncode:
        raise SystemExit("bundle self-test failed:\n" + r.stderr[-3000:])
    return r.stdout.strip().splitlines()[-1]


def at_build_text(manifest, selftest_sha):
    rows = "".join(f'    "{k}": "{manifest[k]}",\n' for k in sorted(manifest))
    return normalized(f'''"""GENERATED by qc/build_bundle.py. Do not edit: rebuild instead.

MANIFEST: SHA-256 of every other project file (line endings and trailing spaces normalized). main.py checks them in the
cloud and stops on any difference. SELFTEST_SHA256: fingerprint of at_stream.selftest() computed by the local engine.
"""
MANIFEST = {{
{rows}}}
BUNDLE_SHA256 = "{bundle_sha(manifest)}"
SELFTEST_SHA256 = "{selftest_sha}"
''')


def main():
    check = "--check" in sys.argv
    files, manifest = build()
    if check:
        for k, v in files.items():
            p = os.path.join(OUT, k)
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != v:
                raise SystemExit(f"qc/cloud/{k} is out of date: run python qc/build_bundle.py")
        p = os.path.join(OUT, "at_build.py")
        if not os.path.exists(p):
            raise SystemExit("qc/cloud/at_build.py is missing")
        txt = open(p, encoding="utf-8").read()
        if f'BUNDLE_SHA256 = "{bundle_sha(manifest)}"' not in txt:
            raise SystemExit("qc/cloud/at_build.py is out of date: run python qc/build_bundle.py")
        extra = {k for k in os.listdir(OUT) if os.path.isfile(os.path.join(OUT, k))} - set(files) - {"at_build.py"}
        if extra:
            raise SystemExit(f"unexpected files in qc/cloud: {sorted(extra)}")
        print("qc/cloud is up to date;", len(files) + 1, "files; bundle", bundle_sha(manifest)[:16])
        return
    os.makedirs(OUT, exist_ok=True)
    for k in os.listdir(OUT):
        if k not in files and k != "at_build.py":
            os.remove(os.path.join(OUT, k))
    for k, v in files.items():
        with open(os.path.join(OUT, k), "w", encoding="utf-8", newline="\n") as f:
            f.write(v)
    sha = selftest_in(OUT)
    with open(os.path.join(OUT, "at_build.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(at_build_text(manifest, sha))
    sizes = {k: os.path.getsize(os.path.join(OUT, k)) for k in os.listdir(OUT) if os.path.isfile(os.path.join(OUT, k))}
    big = {k: n for k, n in sizes.items() if n > MAX_BYTES}
    if len(sizes) > MAX_FILES or big:
        raise SystemExit(f"free-tier limits exceeded: {len(sizes)} files (max {MAX_FILES}); over {MAX_BYTES} bytes: {big}")
    print(f"built qc/cloud: {len(sizes)} files, largest {max(sizes.values())} bytes, bundle {bundle_sha(manifest)[:16]}, self-test {sha[:16]}")


if __name__ == "__main__":
    main()
